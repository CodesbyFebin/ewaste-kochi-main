// A hand-written route can occasionally share a path with one pulled in from
// LEGACY_INDEXED_BLOG_ROUTES/INDEXED_GENERATED_ROUTES (same slug picked
// independently); keep the first occurrence and drop the rest, rather than
// shipping two ROUTES entries -- and two rendered copies during any
// path-keyed processing -- for the same URL.
const seenPaths = new Set<string>();
export const ROUTES: RouteEntry[] = [...BASE_ROUTES, ...GENERATED_PILLAR_ROUTES, ...INDEXED_GENERATED_ROUTES].filter((r) => {
  if (seenPaths.has(r.path)) return false;
  seenPaths.add(r.path);
  return true;
});

export function getHreflang(path: string): { lang: string; href: string }[] | undefined {
  const route = ROUTES.find((r) => r.path === path);
  if (!route?.hreflangPair) return undefined;
  const pair = ROUTES.find((r) => r.path === route.hreflangPair);
  if (!pair) return undefined;

  const enRoute = route.lang === "en-IN" ? route : pair;
  const mlRoute = route.lang === "ml-IN" ? route : pair;

  return [
    { lang: "en-IN", href: new URL(enRoute.path, SITE_URL).toString() },
    { lang: "ml-IN", href: new URL(mlRoute.path, SITE_URL).toString() },
    { lang: "x-default", href: new URL(enRoute.path, SITE_URL).toString() },
  ];
}
